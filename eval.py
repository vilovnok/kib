def build_majority_dataset(
    gt: list[dict],
) -> tuple[list[dict], list[dict]]:
    """
    Голосование проводится по полному объекту result.

    Например, следующие объекты считаются разными вариантами:

    {"agent_code": "tool_a", "tool_needed": "yes"}
    {"agent_code": "tool_a", "tool_needed": "no"}

    Это важно: agent_code и tool_needed оцениваются совместно.
    """

    grouped = defaultdict(list)

    for item in gt:
        item_id = item.get("item_id")
        result = item.get("result")

        if item_id is None or not isinstance(result, dict):
            continue

        grouped[item_id].append(result)

    dataset = []
    ties = []

    for item_id, results in grouped.items():
        result_counts = Counter(
            json.dumps(
                result,
                sort_keys=True,
                ensure_ascii=False,
            )
            for result in results
        )

        max_votes = max(result_counts.values())

        winners = [
            json.loads(result_json)
            for result_json, count in result_counts.items()
            if count == max_votes
        ]

        record = {
            "item_id": item_id,
            "result": winners[0] if len(winners) == 1 else winners,
            "votes": max_votes,
            "total_votes": len(results),
        }

        if len(winners) == 1:
            dataset.append(record)
        else:
            ties.append(record)

    return dataset, ties


