def parse_model_json(response: str) -> dict:
    """
    Извлекает JSON из ответа модели.
    Поддерживает обычный JSON и JSON внутри Markdown-блока.
    """

    cleaned = response.strip()

    # Удаляем Markdown-обёртку, если модель её добавила.
    cleaned = re.sub(
        r"^```(?:json)?\s*",
        "",
        cleaned,
        flags=re.IGNORECASE,
    )
    cleaned = re.sub(r"\s*```$", "", cleaned)

    try:
        parsed = json.loads(cleaned)
    except json.JSONDecodeError:
        # Если вокруг JSON присутствует дополнительный текст,
        # пытаемся извлечь первый JSON-объект.
        match = re.search(r"\{.*\}", cleaned, flags=re.DOTALL)

        if not match:
            raise ValueError(
                f"В ответе модели не найден JSON: {response}"
            )

        parsed = json.loads(match.group(0))

    if not isinstance(parsed, dict):
        raise ValueError("Ответ модели должен быть JSON-объектом")

    return parsed


def validate_model_decision(
    parsed: dict,
    results: list[dict],
) -> dict:
    """
    Проверяет структуру решения и соответствие selected_result
    выбранному исходному варианту.
    """

    decision = parsed.get("decision")

    if decision == "insufficient_context":
        if parsed.get("selected_option") is not None:
            raise ValueError(
                "Для insufficient_context selected_option должен быть null"
            )

        if parsed.get("selected_result") is not None:
            raise ValueError(
                "Для insufficient_context selected_result должен быть null"
            )

        return parsed

    if decision != "selected":
        raise ValueError(f"Неизвестное значение decision: {decision}")

    selected_option = parsed.get("selected_option")

    if not isinstance(selected_option, int):
        raise ValueError("selected_option должен быть целым числом")

    if not 1 <= selected_option <= len(results):
        raise ValueError(
            f"selected_option должен быть от 1 до {len(results)}"
        )

    expected_result = results[selected_option - 1]
    selected_result = parsed.get("selected_result")

    if selected_result != expected_result:
        raise ValueError(
            "selected_result не совпадает с исходным объектом "
            "выбранного варианта"
        )

    return parsed


