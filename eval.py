def build_task_context(task: dict) -> dict:
    tools = task.get("tools", "")

    if isinstance(tools, str):
        available_tools = [
            tool.strip()
            for tool in tools.split(",")
            if tool.strip()
        ]
    elif isinstance(tools, list):
        available_tools = tools
    else:
        available_tools = []

    return {
        "id": task.get("id"),
        "question": task.get("question"),
        "role": task.get("role"),
        "available_tools": available_tools,
    }


def build_user_prompt(
    task: dict,
    results: list[dict],
) -> str:

    task_context = build_task_context(task)

    options = [
        {
            "option": index,
            "result": result,
        }
        for index, result in enumerate(results, start=1)
    ]

    user_prompt = f"""
# ЗАДАЧА

Определи, какой из предложенных вариантов result
наиболее корректен с учётом системных инструкций.

## КОНТЕКСТ КАРТОЧКИ

{json.dumps(task_context, ensure_ascii=False, indent=2)}

## ВАРИАНТЫ ОТВЕТОВ

{json.dumps(options, ensure_ascii=False, indent=2)}

## ИНСТРУКЦИЯ

1. Проанализируй исходный вопрос с учётом роли пользователя.
2. Учитывай только инструменты из available_tools.
3. Сопоставь смысл запроса со справочником инструментов.
4. Проверь специальные ограничения и обязательные параметры.
5. Оцени каждый вариант result целиком.
6. Выбери один наиболее корректный вариант.
7. Не объединяй поля разных вариантов.
8. Верни ответ строго в JSON по формату системного промпта.

Если ни один вариант нельзя обоснованно выбрать из-за недостатка
контекста, используй decision = insufficient_context.
"""

    return user_prompt.strip()


