class GigaChatClient:
    def __init__(self):
        if PROVIDER not in ENDPOINTS:
            raise ValueError(f"Неизвестный PROVIDER: {PROVIDER}")

        self.url = ENDPOINTS[PROVIDER]
        self.model = MODEL
        self.token = self._get_token()
        self.session = requests.Session()

    @staticmethod
    def _get_token() -> str:
        cfg_path = os.path.expanduser(CFG[PROVIDER])
        client = TagmeClientAdvanced(cfg_path)
        return client.client.token

    def invoke(self, system_prompt: str, user_prompt: str) -> str:
        payload = {
            "model": self.model,
            "messages": [
                {
                    "role": "system",
                    "content": system_prompt,
                },
                {
                    "role": "user",
                    "content": user_prompt,
                },
            ],
            "temperature": TEMPERATURE,
            "max_tokens": MAX_TOKENS,
            "profanity_check": False,
        }

        token_refreshed = False

        for attempt in range(1, MAX_RETRIES + 1):
            headers = {
                "Authorization": f"Bearer {self.token}",
                "Content-Type": "application/json",
            }

            try:
                response = self.session.post(
                    self.url,
                    headers=headers,
                    json=payload,
                    verify=False,
                    timeout=TIMEOUT,
                )

                if response.status_code == 401:
                    if not token_refreshed:
                        self.token = self._get_token()
                        token_refreshed = True
                        continue

                    response.raise_for_status()

                if response.status_code == 429 or response.status_code >= 500:
                    if attempt < MAX_RETRIES:
                        time.sleep(2 ** attempt)
                        continue

                response.raise_for_status()

                response_data = response.json()
                choices = response_data.get("choices") or []

                if not choices:
                    raise ValueError(
                        f"Модель вернула пустой choices: {response_data}"
                    )

                content = (
                    choices[0].get("message") or {}
                ).get("content", "")

                if isinstance(content, list):
                    content = " ".join(
                        part.get("text", "")
                        for part in content
                        if isinstance(part, dict)
                    )

                if not isinstance(content, str) or not content.strip():
                    raise ValueError(
                        f"Модель вернула пустой ответ: {response_data}"
                    )

                return content.strip()

            except requests.RequestException:
                if attempt == MAX_RETRIES:
                    raise

                time.sleep(2 ** attempt)

        raise RuntimeError("Не удалось получить ответ от модели")


