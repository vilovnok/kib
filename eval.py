class GigaChatClient:

    def __init__(self):
        self.url = ENDPOINTS[PROVIDER]
        self.model = MODEL
        self.token = self._get_token()

        self.session = requests.Session()

    @staticmethod
    def _get_token() -> str:
        cfg_path = os.path.expanduser(CFG[PROVIDER])

        client = TagmeClientAdvanced(cfg_path)

        return client.client.token

    def invoke(
        self,
        system_prompt: str,
        user_prompt: str,
        task_id: str = None,
        item_id: str = None,
    ) -> str:

        payload = {
            "model": self.model,
            "messages": [
                {
                    "role": "system",
                    "content": system_prompt,
                },
                {
                    "role": "user",
                    "content": user_prompt,
                },
            ],
            "temperature": TEMPERATURE,
            "max_tokens": MAX_TOKENS,
            "profanity_check": False,
        }

        headers = {
            "Authorization": f"Bearer {self.token}",
            "Content-Type": "application/json",
        }

        request_info = (
            f"task_id={task_id} | item_id={item_id}"
        )

        # --------------------------------------------------------
        # ЛОГИРУЕМ ФАКТИЧЕСКИЙ ВХОД МОДЕЛИ
        # --------------------------------------------------------

        logger.info("\n" + "=" * 100)
        logger.info(f"ОТПРАВКА ЗАПРОСА | {request_info}")
        logger.info("=" * 100)

        logger.info(
            "ПАРАМЕТРЫ ЗАПРОСА:\n%s",
            json.dumps(
                {
                    "model": payload["model"],
                    "temperature": payload["temperature"],
                    "max_tokens": payload["max_tokens"],
                    "profanity_check": payload["profanity_check"],
                },
                ensure_ascii=False,
                indent=4
            )
        )

        logger.info(
            "\nSYSTEM PROMPT:\n%s",
            system_prompt
        )

        logger.info(
            "\nUSER PROMPT:\n%s",
            user_prompt
        )

        # Логируем полный payload без HTTP-заголовков и токена.
        logger.info(
            "\nПОЛНЫЙ PAYLOAD:\n%s",
            json.dumps(
                payload,
                ensure_ascii=False,
                indent=4
            )
        )

        token_refreshed = False

        for attempt in range(1, MAX_RETRIES + 1):

            try:

                start_time = time.perf_counter()

                logger.info(
                    f"HTTP REQUEST | {request_info} | "
                    f"Попытка {attempt}/{MAX_RETRIES}"
                )

                response = self.session.post(
                    self.url,
                    headers=headers,
                    json=payload,
                    verify=False,
                    timeout=TIMEOUT,
                )

                elapsed_time = time.perf_counter() - start_time

                # ------------------------------------------------
                # ЛОГИРУЕМ HTTP-ОТВЕТ
                # ------------------------------------------------

                logger.info(
                    f"HTTP RESPONSE | {request_info} | "
                    f"Status: {response.status_code} | "
                    f"Time: {elapsed_time:.2f} sec"
                )

                logger.info(
                    "\nСЫРОЙ ОТВЕТ API:\n%s",
                    response.text
                )

                # ------------------------------------------------
                # ОБНОВЛЕНИЕ ТОКЕНА
                # ------------------------------------------------

                if response.status_code == 401 and not token_refreshed:

                    logger.warning(
                        f"401 Unauthorized | {request_info} | "
                        "Обновляем токен"
                    )

                    self.token = self._get_token()
                    headers["Authorization"] = f"Bearer {self.token}"

                    token_refreshed = True
                    continue

                # ------------------------------------------------
                # ПОВТОР ПРИ ВРЕМЕННЫХ ОШИБКАХ
                # ------------------------------------------------

                if response.status_code == 429 or response.status_code >= 500:

                    if attempt < MAX_RETRIES:

                        sleep_time = 2 ** attempt

                        logger.warning(
                            f"Временная ошибка API: {response.status_code} | "
                            f"Повтор через {sleep_time} сек."
                        )

                        time.sleep(sleep_time)
                        continue

                response.raise_for_status()

                data = response.json()

                choices = data.get("choices") or []

                if not choices:
                    raise ValueError(
                        f"Модель вернула пустой choices: {data}"
                    )

                content = (
                    choices[0].get("message") or {}
                ).get("content", "")

                if isinstance(content, list):
                    content = " ".join(
                        part.get("text", "")
                        for part in content
                        if isinstance(part, dict)
                    )

                if not isinstance(content, str) or not content.strip():
                    raise ValueError(
                        f"Модель вернула пустой ответ: {data}"
                    )

                # ------------------------------------------------
                # ЛОГИРУЕМ ФИНАЛЬНЫЙ ОТВЕТ МОДЕЛИ
                # ------------------------------------------------

                logger.info("\n" + "=" * 100)
                logger.info(f"ОТВЕТ МОДЕЛИ | {request_info}")
                logger.info("=" * 100)

                logger.info(
                    "\nИЗВЛЕЧЁННЫЙ CONTENT:\n%s",
                    content
                )

                logger.info(
                    f"Время выполнения: {elapsed_time:.2f} сек."
                )

                logger.info("=" * 100 + "\n")

                return content

            except requests.RequestException:

                logger.exception(
                    f"HTTP ERROR | {request_info} | "
                    f"Попытка {attempt}/{MAX_RETRIES}"
                )

                if attempt == MAX_RETRIES:
                    raise

                sleep_time = 2 ** attempt

                logger.info(
                    f"Повтор запроса через {sleep_time} сек."
                )

                time.sleep(sleep_time)

        raise RuntimeError(
            "Не удалось получить ответ от модели"
        )


